"""
再帰関数
ABC473 D問題参照
"""

N = 3
K = 8
ans = []
tochuu = []

def dfs(i, nokori):
    if i > N:                      # N個すべて決め終わった
        if nokori == 0:            # ちょうど使い切っていれば成功
            ans.append(" ".join(map(str, tochuu)))
        return
    for v in range(nokori // i + 1):   # i番目に入れる値を0から昇順に試す
        tochuu.append(v)
        dfs(i + 1, nokori - i * v)
        tochuu.pop()                   # 戻す

dfs(1, K)
print("\n".join(ans))

