import sys
from bisect import bisect_left, bisect_right
from collections import Counter, defaultdict, deque
from heapq import heappop, heappush
from itertools import permutations

input = sys.stdin.readline

INF = 10**18
MOD = 998244353

# M = 2 固定
# M = 0,1 でMの値はAとBそれぞれの要素が持てる数値のこと
N, M = map(int, input().split())

A = list(map(int , input().split()))
B = list(map(int , input().split()))

count=0
a = A[0]

for i in range(N-1):
    if (a + A[i+1]) % M != B[i]:
        # 等しくないならば、更新する必要がある
        a = (B[i] - a) % M
        count +=1 # 更新回数を積算
    else:
        # 等しいならばaは次のi番目のAに書き換える
        a = A[i+1]

print(min(count, N- count))

# やりたかった意図としては、和がBiと一致しない場合は、一致させるために1を足す必要があるので、
# その回数を計算して、あとは重複分を引けばいい、と思っていました。
# しかしどれが重複しているかを判別するコートが書けませんでした。

# その発想自体は正しい方向を向いています。ただ「重複を後から引く」のが難しいのは、重複の構造が局所的ではないからです。
# A[i] を 1 つ書き換えると B[i-1] と B[i] の 2 つの条件が同時に動きます。なので「不一致が 2 つ隣り合っていれば 1 回で済む」だけでなく、不一致が連鎖して並んでいる場合は、どこを起点に書き換えるかで結果が変わります。
# 不一致の個数だけを見て後から引き算しようとすると、この連鎖を再現できません。
# 解決策は、後から引くのではなく、その場で直しながら進むことです。
# 書き換えた結果を次のループに持ち越せば、重複は自動的に解消されます。

# これが「もう一つの候補」の処理です。実は条件を満たす A は 2 通りしかありません。
# A[0] を決めれば A[i+1] = (B[i] - A[i]) % M で全体が芋づる式に確定するからです。
# 上のループは A[0] を書き換えない側の候補を計算しています。
# もう一方は、その候補の全ビットを反転したもの（M=2 では両方を反転しても和の偶奇は変わらないので、
# これも条件を満たします）。

# 2 つの候補は N 箇所すべてで異なるので、元の A との距離の和は必ず N になります。
# だから N - count でもう一方が求まります。
# なお min(count, N - count) は M=2 だから成り立つ式です。
# 一般の M では候補が M 通りあるので、A[0] を 0 から M-1 まで振って同じループを回し、最小値を取る形になります。